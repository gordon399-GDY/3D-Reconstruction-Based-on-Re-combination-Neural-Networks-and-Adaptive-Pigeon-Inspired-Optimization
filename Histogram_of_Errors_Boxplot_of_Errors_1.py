# ==================== 新增：计算中位数、IQR、离群点的函数 ====================
def compute_median_iqr(errors):
    """计算中位数和四分位距（IQR）"""
    median = np.median(errors)
    q1 = np.percentile(errors, 25)
    q3 = np.percentile(errors, 75)
    iqr = q3 - q1
    return median, iqr, q1, q3


def find_outliers(errors):
    """找出离群点（基于1.5倍IQR规则）"""
    q1 = np.percentile(errors, 25)
    q3 = np.percentile(errors, 75)
    iqr = q3 - q1
    lower = q1 - 1.5 * iqr
    upper = q3 + 1.5 * iqr
    outliers = errors[(errors < lower) | (errors > upper)]
    return outliers


