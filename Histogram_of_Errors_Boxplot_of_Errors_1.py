# 计算欧几里得距离
def calculate_euclidean_distances(real, rbp, bp):
    """计算两组误差的欧几里得距离"""
    distances_rbp = np.linalg.norm(real - rbp, axis=1)
    distances_bp = np.linalg.norm(real - bp, axis=1)
    return distances_rbp, distances_bp


